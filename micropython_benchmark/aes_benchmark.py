RCON = [0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36]

def xtime(x):
    r = (x << 1) & 0xFF
    return r ^ 0x1B if x & 0x80 else r

def gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return p

def aes128_key_expansion(key):
    w = [[0, 0, 0, 0] for _ in range(4 * AES_ROUND_KEYS)]
    for i in range(4):
        for j in range(4):
            w[i][j] = key[4 * i + j]
    for i in range(4, 4 * AES_ROUND_KEYS):
        temp = list(w[i - 1])
        if i % 4 == 0:
            t0 = temp[0]
            temp[0] = SBOX[temp[1]] ^ RCON[i // 4 - 1]
            temp[1] = SBOX[temp[2]]
            temp[2] = SBOX[temp[3]]
            temp[3] = SBOX[t0]
        w[i] = [w[i - 4][j] ^ temp[j] for j in range(4)]

    round_keys = [bytearray(16) for _ in range(AES_ROUND_KEYS)]
    for r in range(AES_ROUND_KEYS):
        for c in range(4):
            for j in range(4):
                round_keys[r][4 * c + j] = w[4 * r + c][j]
    return round_keys

def add_round_key(state, rk):
    for i in range(16):
        state[i] ^= rk[i]

def sub_bytes(state):
    for i in range(16):
        state[i] = SBOX[state[i]]

def inv_sub_bytes(state):
    for i in range(16):
        state[i] = INV_SBOX[state[i]]

def shift_rows(state):
    tmp = bytes(state)
    for c in range(4):
        for r in range(4):
            state[4 * c + r] = tmp[4 * ((c + r) % 4) + r]

def inv_shift_rows(state):
    tmp = bytes(state)
    for c in range(4):
        for r in range(4):
            state[4 * c + r] = tmp[4 * ((c - r + 4) % 4) + r]

def mix_columns(state):
    for c in range(4):
        o = 4 * c
        s0, s1, s2, s3 = state[o], state[o+1], state[o+2], state[o+3]
        state[o]   = xtime(s0) ^ (xtime(s1) ^ s1) ^ s2 ^ s3
        state[o+1] = s0 ^ xtime(s1) ^ (xtime(s2) ^ s2) ^ s3
        state[o+2] = s0 ^ s1 ^ xtime(s2) ^ (xtime(s3) ^ s3)
        state[o+3] = (xtime(s0) ^ s0) ^ s1 ^ s2 ^ xtime(s3)

def inv_mix_columns(state):
    for c in range(4):
        o = 4 * c
        s0, s1, s2, s3 = state[o], state[o+1], state[o+2], state[o+3]
        state[o]   = gmul(s0,14) ^ gmul(s1,11) ^ gmul(s2,13) ^ gmul(s3,9)
        state[o+1] = gmul(s0,9)  ^ gmul(s1,14) ^ gmul(s2,11) ^ gmul(s3,13)
        state[o+2] = gmul(s0,13) ^ gmul(s1,9)  ^ gmul(s2,14) ^ gmul(s3,11)
        state[o+3] = gmul(s0,11) ^ gmul(s1,13) ^ gmul(s2,9)  ^ gmul(s3,14)

def aes128_encrypt_block(rk, pt, ct):
    state = bytearray(pt)
    add_round_key(state, rk[0])
    for rnd in range(1, AES_ROUNDS):
        sub_bytes(state)
        shift_rows(state)
        mix_columns(state)
        add_round_key(state, rk[rnd])
    sub_bytes(state)
    shift_rows(state)
    add_round_key(state, rk[AES_ROUNDS])
    ct[:] = state

def aes128_decrypt_block(rk, ct, pt):
    state = bytearray(ct)
    add_round_key(state, rk[AES_ROUNDS])
    for rnd in range(AES_ROUNDS - 1, 0, -1):
        inv_shift_rows(state)
        inv_sub_bytes(state)
        add_round_key(state, rk[rnd])
        inv_mix_columns(state)
    inv_shift_rows(state)
    inv_sub_bytes(state)
    add_round_key(state, rk[0])
    pt[:] = state

def aes128_cbc_encrypt(rk, iv, src, dst, length):
    prev = iv
    block = bytearray(16)
    ct_block = bytearray(16)
    for i in range(0, length, AES_BLOCK_SIZE):
        for j in range(16):
            block[j] = src[i + j] ^ prev[j]
        aes128_encrypt_block(rk, block, ct_block)
        dst[i:i + 16] = ct_block
        prev = dst[i:i + 16]

def aes128_cbc_decrypt(rk, iv, src, dst, length):
    prev = iv
    pt_block = bytearray(16)
    for i in range(0, length, AES_BLOCK_SIZE):
        ct_block = src[i:i + 16]
        aes128_decrypt_block(rk, ct_block, pt_block)
        for j in range(16):
            dst[i + j] = pt_block[j] ^ prev[j]
        prev = ct_block

